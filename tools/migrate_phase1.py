#!/usr/bin/env python3
"""One-time, lossless structural migration of the original standalone portfolio.

Only run on the original index.html. The existing HTML text, CSS rules, JS
behavior and embedded image bytes are not rewritten: they are relocated.
"""
from __future__ import annotations
import base64
import hashlib
import json
from pathlib import Path
import re
import subprocess

ROOT = Path(__file__).resolve().parents[1]
INDEX = ROOT / 'index.html'
HTML = INDEX.read_text(encoding='utf-8')
if 'assets/site.css' in HTML or 'assets/site.js' in HTML:
    raise SystemExit('Already migrated: refusing a second pass')

STYLE = re.search(r'<style\b[^>]*>(.*?)</style>', HTML, re.S | re.I)
SCRIPT = re.search(r'<script\b[^>]*>(.*?)</script>', HTML, re.S | re.I)
if not STYLE or not SCRIPT or len(re.findall(r'<style\b', HTML, re.I)) != 1 or len(re.findall(r'<script\b', HTML, re.I)) != 1:
    raise SystemExit('Expected exactly one inline style and one inline script')
js = SCRIPT.group(1)
start = js.find('    const translations = {')
end = js.find('    // Apply visual identities', start)
if start < 0 or end < 0:
    raise SystemExit('Cannot locate the four-language translation expressions')
source_obj = js[start:end]
node = subprocess.run(
    ['node', '-e', "const vm=require('node:vm');let s='';process.stdin.on('data',b=>s+=b);process.stdin.on('end',()=>process.stdout.write(JSON.stringify(vm.runInNewContext(s+String.fromCharCode(10)+'translations'))))"],
    input=source_obj, encoding='utf-8', capture_output=True, check=True)
translations = json.loads(node.stdout)
if set(translations) != {'en', 'es', 'ca', 'fr'}:
    raise SystemExit('Locale keys do not match expected en/es/ca/fr')

# Assets preserve decoded image bytes exactly, despite being moved out of HTML.
images = ROOT / 'assets' / 'images'
images.mkdir(parents=True, exist_ok=True)
manifest = []
pattern = re.compile(r'src="data:image/(png|jpeg|gif|webp|svg\+xml);base64,([^"]+)"', re.I)
def extract_image(m):
    extension = {'jpeg': 'jpg', 'svg+xml': 'svg'}.get(m.group(1).lower(), m.group(1).lower())
    raw = base64.b64decode(m.group(2), validate=True)
    digest = hashlib.sha256(raw).hexdigest()
    rel = f'assets/images/image-{len(manifest)+1:02d}-{digest[:12]}.{extension}'
    (ROOT / rel).write_bytes(raw)
    manifest.append({'path': rel, 'sha256': digest, 'bytes': len(raw), 'mime': f'image/{m.group(1).lower()}'})
    return f'src="./{rel}"'
HTML = pattern.sub(extract_image, HTML)
if len(manifest) != 20 or 'src="data:image/' in HTML:
    raise SystemExit('Expected exactly 20 embedded images')

(ROOT / 'assets').mkdir(exist_ok=True)
(ROOT / 'assets/site.css').write_text(STYLE.group(1) + '\n', encoding='utf-8')
(ROOT / 'assets/site.js').write_text(
    js[:start] + '    const translations = window.PortfolioTranslations;\n\n' + js[end:] + '\n',
    encoding='utf-8')
content_dir = ROOT / 'cms/content'
content_dir.mkdir(parents=True, exist_ok=True)
(content_dir / 'translations.json').write_text(json.dumps(translations, ensure_ascii=False, indent=2) + '\n', encoding='utf-8')
(content_dir / 'translations.js').write_text(
    '// Generated from translations.json. Do not edit this file by hand.\n' +
    'window.PortfolioTranslations = ' + json.dumps(translations, ensure_ascii=False, separators=(',', ':')) + ';\n',
    encoding='utf-8')
(ROOT / 'cms/assets-manifest.json').write_text(json.dumps(manifest, indent=2) + '\n', encoding='utf-8')

# Preserve the original exact markup and position of the stylesheet and script.
HTML = HTML.replace(STYLE.group(0), '<link rel="stylesheet" href="./assets/site.css">', 1)
HTML = HTML.replace(SCRIPT.group(0), '<script src="./cms/content/translations.js"></script>\n  <script src="./assets/site.js"></script>', 1)
INDEX.write_text(HTML, encoding='utf-8')
print(f'Extracted CSS, JS, {sum(map(len, translations.values()))} translation keys across four locales, {len(manifest)} images')
